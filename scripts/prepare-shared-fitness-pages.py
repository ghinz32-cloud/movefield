"""Replace both owned shared-app previews; preserve the original Movefield app."""
import argparse,datetime,hashlib,io,json,pathlib,re,shutil,subprocess,tarfile
ROOT=pathlib.Path(__file__).resolve().parents[1];RUNTIME=ROOT/'.sites-runtime'
parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--base-commit',required=True);args=parser.parse_args()
if not re.fullmatch(r'[a-f0-9]{40}',args.base_commit):parser.error('Use the inspected full Pages commit.')
candidate=RUNTIME/'fitness-pages-candidate';marker=RUNTIME/'fitness-pages-candidate.generated'
if candidate.exists():
 if not marker.exists():raise RuntimeError('Refusing to replace an unmarked candidate.')
 shutil.rmtree(candidate)
candidate.mkdir();marker.write_text('Generated by prepare-shared-fitness-pages.py\n')
with tarfile.open(fileobj=io.BytesIO(subprocess.check_output(['git','archive',args.base_commit],cwd=ROOT))) as archive:archive.extractall(candidate,filter='data')
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
original={str(p.relative_to(candidate)):sha(p) for p in candidate.rglob('*') if p.is_file()}
source=json.loads((RUNTIME/'candidate-receipt-current.json').read_text());commit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
for folder in ['review','grizzly']:
 target=candidate/folder;name=folder+'-manifest.json';previous=json.loads((target/name).read_text())
 if previous.get('schema')!=1 or previous.get('base')!='/movefield/'+folder+'/':raise RuntimeError('Unexpected ownership manifest: '+folder)
 actual={str(p.relative_to(target)) for p in target.rglob('*') if p.is_file()}
 expected=set(previous['files'])|{name}
 if expected-actual:raise RuntimeError('Missing files in owned directory: '+folder)
 # Older publication left four hashed chunks outside its manifest. Preserve
 # unlisted compiled assets rather than deleting an unclaimed file. All other
 # unexpected paths still fail closed, and previously retained chunks stay.
 legacy=sorted(set(previous.get('retained_legacy_files',[]))|(actual-expected))
 if any(not re.fullmatch(r'assets/[A-Za-z0-9._-]+-[A-Za-z0-9_-]{8,}\.(?:js|css)',path) or path not in actual for path in legacy):raise RuntimeError('Unexpected noncompiled files in owned directory: '+folder)
 legacy_bytes={path:(target/path).read_bytes() for path in legacy}
 for path,expected in previous['files'].items():
  p=target/path
  if p.is_symlink() or '..' in pathlib.PurePosixPath(path).parts or not p.resolve().is_relative_to(target.resolve()) or sha(p)!=expected:raise RuntimeError('Owned artifact differs: '+path)
 shutil.rmtree(target);shutil.copytree(RUNTIME/('github-pages-'+folder),target)
 for path,data in legacy_bytes.items():
  retained=target/path
  if retained.exists() and retained.read_bytes()!=data:raise RuntimeError('Compiled asset name collision: '+path)
  retained.parent.mkdir(parents=True,exist_ok=True);retained.write_bytes(data)
 for extra in ['_headers','.assetsignore']:
  if (target/extra).exists():(target/extra).unlink()
 (target/'.nojekyll').write_text('')
 files={str(p.relative_to(target)):sha(p) for p in sorted(target.rglob('*')) if p.is_file()}
 manifest={'schema':1,'base':'/movefield/'+folder+'/','brand':'Grizzly Fitness' if folder=='grizzly' else 'Movefield','profile_scope':'Separate brand profile, database, preferences and offline cache. Training code is shared.','application_source_sha256':source['application_source_sha256'],'source_commit':commit,'files':files}
 if legacy:manifest['retained_legacy_files']=legacy
 if folder=='grizzly':manifest.update(official_logo_retrieved=False,logo_supplied_by_user=True,logo_source='User-supplied JPEG, unchanged.',logo_sha256=sha(target/'brand/grizzly-fitness-logo.jpg'))
 (target/name).write_text(json.dumps(manifest,indent=2)+'\n')
if any(p.is_symlink() for p in candidate.rglob('*')):raise RuntimeError('No symlink may be published.')
for name,expected in original.items():
 if not name.startswith(('review/','grizzly/')) and sha(candidate/name)!=expected:raise RuntimeError('Original application altered: '+name)
main=json.loads((candidate/'pages-manifest.json').read_text())
for path,expected in main['assets'].items():
 if not path.startswith('/movefield/') or sha(candidate/path.removeprefix('/movefield/'))!=expected:raise RuntimeError('Original pinned asset differs: '+path)
files={str(p.relative_to(candidate)):sha(p) for p in sorted(candidate.rglob('*')) if p.is_file()}
receipt={'prepared_at':datetime.datetime.now(datetime.timezone.utc).isoformat(),'base_pages_commit':args.base_commit,'current_source_commit':commit,'application_source_sha256':source['application_source_sha256'],'preserved_original_files':sum(not p.startswith(('review/','grizzly/')) for p in original),'deleted_files':sorted(set(original)-set(files)),'candidate_files':files,'uploaded':False}
(RUNTIME/'fitness-pages-candidate-receipt.json').write_text(json.dumps(receipt,indent=2)+'\n')
print(json.dumps({k:receipt[k] for k in ['base_pages_commit','current_source_commit','preserved_original_files','uploaded']}))
