"""Prepare a linked review addition while preserving the existing Pages app.

Local artifacts only. No Git index changes, commits, pushes or network requests.
"""
import argparse,datetime,hashlib,io,json,pathlib,re,shutil,subprocess,tarfile
ROOT=pathlib.Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--base-commit',required=True);args=parser.parse_args()
if not re.fullmatch(r'[a-f0-9]{40}',args.base_commit):parser.error('Use the inspected full Pages commit.')
review=ROOT/'.sites-runtime/github-pages-review';candidate=ROOT/'.sites-runtime/github-pages-candidate'
marker=ROOT/'.sites-runtime/github-pages-candidate.generated'
if candidate.exists():
 if not marker.exists():raise RuntimeError('Refusing to replace an unmarked candidate')
 shutil.rmtree(candidate)
candidate.mkdir();marker.write_text('Generated by prepare-github-review.py\n')
archive=subprocess.check_output(['git','archive',args.base_commit],cwd=ROOT)
with tarfile.open(fileobj=io.BytesIO(archive)) as tar:tar.extractall(candidate,filter='data')
if (candidate/'review').exists():raise RuntimeError('An existing review directory requires inspection before replacement')
shutil.copytree(review,candidate/'review')
for name in ['_headers','.assetsignore']:
 path=candidate/'review'/name
 if path.exists():path.unlink()
(candidate/'review/.nojekyll').write_text('')
def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def js_json(value):return json.dumps(value,separators=(',',':'),ensure_ascii=False)
files={str(p.relative_to(candidate/'review')):digest(p) for p in sorted((candidate/'review').rglob('*')) if p.is_file()}
for path in (candidate/'review').rglob('*'):
 if path.is_symlink():raise RuntimeError('No symlinks may be published')
source=json.loads((ROOT/'.sites-runtime/candidate-receipt-current.json').read_text())
review_manifest={'schema':1,'base':'/movefield/review/','profile_scope':'Separate review storage; current app records are not migrated automatically.','application_source_sha256':source['application_source_sha256'],'source_commit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'files':files}
(candidate/'review/review-manifest.json').write_text(json.dumps(review_manifest,indent=2)+'\n')
html=(candidate/'index.html').read_text()
if 'id="movefield-review-link"' in html:raise RuntimeError('Inspect the existing review link before changing it')
banner='<div id="movefield-review-link" style="position:sticky;top:0;z-index:1000;display:flex;justify-content:center;gap:12px;flex-wrap:wrap;padding:12px;background:#eaffce;color:#14352b;font:600 16px/1.4 system-ui;border-bottom:1px solid #aabf97"><a href="/movefield/review/" style="color:inherit;text-decoration:underline">See latest additions</a><span>Separate review profile</span></div>'
html,count=re.subn(r'(<body\b[^>]*>)',lambda match:match[0]+banner,html,count=1)
if count!=1:raise RuntimeError('The existing page has no body')
(candidate/'index.html').write_text(html)
manifest_path=candidate/'pages-manifest.json';manifest=json.loads(manifest_path.read_text())
def version(manifest):return hashlib.sha256(js_json({key:manifest[key] for key in ['workerTemplateSha256','coachingWorker','assets']}).encode()).hexdigest()
if version(manifest)!=manifest['version']:raise RuntimeError('The original manifest version algorithm differs; inspect before changing it')
manifest['assets']['/movefield/index.html']=digest(candidate/'index.html');manifest['version']=version(manifest)
manifest_path.write_text(json.dumps(manifest,indent=2)+'\n')
worker_path=candidate/'sw.js';worker=worker_path.read_text();worker,count=re.subn(r'^const MANIFEST=.*;$',lambda _: 'const MANIFEST='+js_json(manifest)+';',worker,count=1,flags=re.M)
if count!=1:raise RuntimeError('The original worker manifest declaration differs')
worker_path.write_text(worker)
for path,expected in manifest['assets'].items():
 if not path.startswith('/movefield/'):raise RuntimeError('Unexpected original asset scope')
 if digest(candidate/path.removeprefix('/movefield/'))!=expected:raise RuntimeError('Original pinned asset differs: '+path)
paths={str(p.relative_to(candidate)):digest(p) for p in sorted(candidate.rglob('*')) if p.is_file()}
report={'prepared_at':datetime.datetime.now(datetime.timezone.utc).isoformat(),'base_pages_commit':args.base_commit,'current_source_commit':review_manifest['source_commit'],'application_source_sha256':source['application_source_sha256'],'original_files_changed':['index.html','pages-manifest.json','sw.js'],'original_manifest_version':manifest['version'],'review_files':len(files)+1,'candidate_files':paths,'uploaded':False}
(ROOT/'.sites-runtime/github-pages-candidate-receipt.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps({key:report[key] for key in ['base_pages_commit','current_source_commit','original_files_changed','review_files','uploaded']}))
