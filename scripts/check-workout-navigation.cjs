const assert = require('node:assert/strict');
const path = require('node:path');
const {createTsxLoader} = require('./lib/component-hook-harness.cjs');
const root = path.resolve(__dirname, '..');
const loader = createTsxLoader(root);
const E = loader.load(path.join(root, 'mobile/src/mobile-engine.ts'));
const N = loader.load(path.join(root, 'lib/workout-navigation.ts'));
let state = E.adoptPlan(E.emptyDemo(), E.previewPlan(E.FOUNDATION).plan);
state = E.startWorkout(state, state.plan.sessions[0].id);
const w = state.active;
const before = JSON.stringify(state);
const progress = N.workoutExerciseProgress(state, w);
assert.equal(progress.length, w.targets.length);
assert.ok(progress.every(row => row.loggedSets === 0 && !row.complete));
assert.equal(N.nextWorkoutExercise(state, w, w.targets[0].exerciseId), 1);
assert.equal(N.nextWorkoutExercise(state, w, w.targets.at(-1).exerciseId), N.WORKOUT_REMAINING);
const done = {...w, sets: w.sets.map(set => ({...set, reps: 8, done: true}))};
assert.ok(N.workoutExerciseProgress(state, done).every(row => row.complete));
assert.equal(N.nextWorkoutExercise(state, done, w.targets[0].exerciseId), N.WORKOUT_COMPLETE);
assert.equal(N.nextWorkoutExercise(state, done, 'removed-exercise'), N.WORKOUT_OVERVIEW);
const missing = {...done, sets: done.sets.slice(1)};
assert.equal(N.workoutExerciseProgress(state, missing)[0].complete, false);
assert.equal(N.workoutExerciseProgress(state, missing)[0].remainingSets, 1);
const signature = N.workoutCompletionSignature(state, w);
assert.notEqual(N.workoutCompletionSignature(state, done), signature);
assert.equal(N.workoutCompletionSignature(state, {...w, details: {}}), signature);
assert.deepEqual(N.workoutExerciseProgress({...state, plan: null, saved: [state.plan]}, {...w, targets: undefined}), progress);
assert.equal(N.workoutExerciseProgress({...state, plan: null, saved: []}, {...w, targets: undefined}).length, progress.length);
assert.equal(JSON.stringify(state), before);
console.log('PASS workout navigation: overview, forward/remaining/complete paths, missing sets, completion signatures, archived/legacy targets and immutable input.');
